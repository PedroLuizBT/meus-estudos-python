n1 = float(input('Digite o primeiro número: '))
n2 = float(input('Digite o segundo número: '))
n3 = float(input('Digite o terceiro número: '))

soma = n1 + n2 + n3
subtracao = n1 - n2 - n3
divisao = n1 / n2 / n3
multiplicacao = n1 * n2 * n3

print('A soma entre {} e {} e {} é: {}'.format(n1, n2, n3, soma))
print('A subtração entre {} e {} e {} é: {}'.format(n1, n2, n3, subtracao))
print('A divisão entre {} e {} e {} é: {}'.format(n1, n2, n3, divisao))
print('A multiplicação entre {} e {} e {} é: {}'.format(n1, n2, n3, multiplicacao))